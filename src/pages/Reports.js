import React, {
  useEffect,
  useState,
} from "react";

import "./Dashboard.css";

import Sidebar from "../components/Sidebar";
import Topbar from "../components/Topbar";

import { getData } from "../utils/storage";

import {
  FaFileAlt,
  FaLeaf,
  FaDownload,
} from "react-icons/fa";


function Reports() {

  const [data, setData] =
    useState([]);


  // ==========================================
  // LOAD CURRENT USER DATA
  // ==========================================

  useEffect(() => {

    const savedData =
      getData();

    setData(savedData);

  }, []);


  // ==========================================
  // CALCULATE TOTALS
  // ==========================================

  const totalElectricity =
    data.reduce(
      (sum, item) =>
        sum +
        Number(item.electricity || 0),
      0
    );


  const totalWater =
    data.reduce(
      (sum, item) =>
        sum +
        Number(item.water || 0),
      0
    );


  const totalFuel =
    data.reduce(
      (sum, item) =>
        sum +
        Number(item.fuel || 0),
      0
    );


  const totalWaste =
    data.reduce(
      (sum, item) =>
        sum +
        Number(item.waste || 0),
      0
    );


  const totalCarbon =
    data.reduce(
      (sum, item) =>
        sum +
        Number(item.carbon || 0),
      0
    );


  // ==========================================
  // DOWNLOAD REPORT
  // ==========================================

  const downloadReport = () => {

    if (data.length === 0) {

      alert(
        "No data available. Please calculate your carbon footprint first."
      );

      return;
    }


    const report = `
========================================
              ECOTRACK
       SUSTAINABILITY REPORT
========================================

Total Records:
${data.length}

----------------------------------------
RESOURCE CONSUMPTION
----------------------------------------

Electricity:
${totalElectricity.toFixed(2)} kWh

Water:
${totalWater.toFixed(2)} Litres

Fuel:
${totalFuel.toFixed(2)} Litres

Waste:
${totalWaste.toFixed(2)} Kg

----------------------------------------
CARBON FOOTPRINT
----------------------------------------

Total Carbon Footprint:
${totalCarbon.toFixed(2)} kg CO₂

----------------------------------------
RECORD HISTORY
----------------------------------------

${data
  .slice()
  .reverse()
  .map(
    (item) =>
      `Date: ${item.date}
Electricity: ${item.electricity} kWh
Water: ${item.water} Litres
Fuel: ${item.fuel} Litres
Waste: ${item.waste} Kg
Carbon: ${item.carbon} kg CO₂
----------------------------------------`
  )
  .join("\n")}

Generated by EcoTrack

Track Today. Sustain Tomorrow.
`;


    // Create file

    const blob = new Blob(
      [report],
      {
        type: "text/plain",
      }
    );


    const url =
      URL.createObjectURL(blob);


    const link =
      document.createElement("a");


    link.href = url;


    link.download =
      "EcoTrack-Sustainability-Report.txt";


    document.body.appendChild(link);


    link.click();


    document.body.removeChild(link);


    URL.revokeObjectURL(url);
  };


  return (

    <div className="dashboard-layout">

      <Sidebar />


      <div className="main-content">

        <Topbar />


        {/* =========================
            HEADER
        ========================== */}

        <div style={styles.header}>

          <div>

            <p style={styles.overline}>
              SUSTAINABILITY REPORT
            </p>


            <h1 style={styles.title}>
              Reports
            </h1>


            <p style={styles.subtitle}>
              View and download your EcoTrack
              sustainability report.
            </p>

          </div>


          <FaFileAlt
            style={styles.headerIcon}
          />

        </div>


        {/* =========================
            REPORT CARD
        ========================== */}

        <div style={styles.reportCard}>

          <FaLeaf
            style={styles.leaf}
          />


          <h2
            style={styles.reportTitle}
          >
            EcoTrack Sustainability Report
          </h2>


          <p
            style={styles.reportText}
          >
            Your environmental activity is
            summarized using the data recorded
            from your Dashboard.
          </p>


          {/* Summary */}

          <div style={styles.summary}>

            <div
              style={styles.summaryItem}
            >

              <span
                style={styles.summaryLabel}
              >
                Records
              </span>

              <strong
                style={styles.summaryValue}
              >
                {data.length}
              </strong>

            </div>


            <div
              style={styles.summaryItem}
            >

              <span
                style={styles.summaryLabel}
              >
                Electricity
              </span>

              <strong
                style={styles.summaryValue}
              >
                {totalElectricity.toFixed(2)}
                {" "}kWh
              </strong>

            </div>


            <div
              style={styles.summaryItem}
            >

              <span
                style={styles.summaryLabel}
              >
                Water
              </span>

              <strong
                style={styles.summaryValue}
              >
                {totalWater.toFixed(2)}
                {" "}L
              </strong>

            </div>


            <div
              style={styles.summaryItem}
            >

              <span
                style={styles.summaryLabel}
              >
                Fuel
              </span>

              <strong
                style={styles.summaryValue}
              >
                {totalFuel.toFixed(2)}
                {" "}L
              </strong>

            </div>


            <div
              style={styles.summaryItem}
            >

              <span
                style={styles.summaryLabel}
              >
                Waste
              </span>

              <strong
                style={styles.summaryValue}
              >
                {totalWaste.toFixed(2)}
                {" "}Kg
              </strong>

            </div>


            <div
              style={styles.summaryItem}
            >

              <span
                style={styles.summaryLabel}
              >
                Carbon
              </span>

              <strong
                style={styles.summaryValue}
              >
                {totalCarbon.toFixed(2)}
                {" "}kg CO₂
              </strong>

            </div>

          </div>


          {/* Download button */}

          {data.length > 0 ? (

            <button
              onClick={downloadReport}
              style={styles.downloadButton}
            >

              <FaDownload />

              Download Report

            </button>

          ) : (

            <div
              style={styles.noDataBox}
            >

              <p
                style={styles.noData}
              >
                No sustainability data available yet.
              </p>


              <p
                style={styles.noDataSub}
              >
                Go to Dashboard and calculate
                your carbon footprint first.
              </p>

            </div>

          )}

        </div>


        {/* =========================
            REPORT HISTORY
        ========================== */}

        {data.length > 0 && (

          <div
            style={styles.historyCard}
          >

            <h2
              style={styles.historyTitle}
            >
              Report History
            </h2>


            {data
              .slice()
              .reverse()
              .map((item) => (

                <div
                  key={item.id}
                  style={styles.historyRow}
                >

                  <div>

                    <strong>
                      {item.date}
                    </strong>


                    <p
                      style={
                        styles.historyDetails
                      }
                    >
                      Electricity:{" "}
                      {item.electricity} kWh
                      {" • "}
                      Water:{" "}
                      {item.water} L
                      {" • "}
                      Fuel:{" "}
                      {item.fuel} L
                      {" • "}
                      Waste:{" "}
                      {item.waste} Kg
                    </p>

                  </div>


                  <strong
                    style={
                      styles.historyCarbon
                    }
                  >
                    {item.carbon} kg CO₂
                  </strong>

                </div>

              ))}

          </div>

        )}

      </div>

    </div>
  );
}


